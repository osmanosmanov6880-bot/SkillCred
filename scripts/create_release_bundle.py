#!/usr/bin/env python3
"""Create a source ZIP and path-addressed Markdown dump without local state."""
from __future__ import annotations

import argparse
import re
import tomllib
import zipfile
from pathlib import Path, PurePosixPath

EXCLUDED_PARTS = {
    ".git", ".pytest_cache", "__pycache__", ".venv", "venv", "build", "dist",
    ".mypy_cache", ".ruff_cache", ".tox", "skillcred-data", "demo-output",
    "compliance-results", ".idea", ".vscode",
}
EXCLUDED_NAMES = {
    ".coverage", "status-state.json", "status-state.lock", "issuer-private-key.b64",
    "credential.json", "issued-credential.json", "tokens.json", "clients.enc",
    "trusted-issuers.json", "impact.sqlite3", ".coverage-final.json", "coverage.xml",
}
EXCLUDED_SUFFIXES = {".pyc", ".pyo", ".scw", ".wallet", ".pem", ".key"}


def excluded(path: Path, root: Path) -> bool:
    relative = path.relative_to(root)
    if set(relative.parts) & EXCLUDED_PARTS:
        return True
    if any(part.endswith(".egg-info") for part in relative.parts):
        return True
    name = path.name
    if name in EXCLUDED_NAMES or path.suffix.lower() in EXCLUDED_SUFFIXES:
        return True
    if name.startswith(".env") and name != ".env.example":
        return True
    if name.endswith((".sqlite", ".sqlite3", ".db")):
        return True
    return False


def source_files(root: Path) -> list[Path]:
    result = [path for path in root.rglob("*") if path.is_file() and not excluded(path, root)]
    return sorted(result, key=lambda item: item.relative_to(root).as_posix())


def create_bundle(root: Path, output_dir: Path) -> tuple[Path, Path, list[str]]:
    root = root.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    with (root / "pyproject.toml").open("rb") as stream:
        version = tomllib.load(stream)["project"]["version"]
    paths = source_files(root)
    names = [path.relative_to(root).as_posix() for path in paths]
    zip_path = output_dir / f"SkillCred-{version}.zip"
    dump_path = output_dir / f"SkillCred-{version}-source.md"
    prefix = f"skillcred-{version}"
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path, name in zip(paths, names, strict=True):
            archive.write(path, f"{prefix}/{name}")
    with dump_path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(f"# SkillCred {version} — complete source dump\n\n")
        stream.write(f"Files: {len(names)}. Generated by `scripts/create_release_bundle.py`.\n\n")
        stream.write("Generated source dump only. Verify the sibling SHA-256 manifest before use.\n\n")
        for path, name in zip(paths, names, strict=True):
            data = path.read_bytes()
            try:
                contents = data.decode("utf-8")
            except UnicodeDecodeError:
                contents = f"[binary file: {len(data)} bytes; see ZIP artifact]"
            fence_length = max((len(match.group(0)) for match in re.finditer(r"`+", contents)), default=0) + 1
            fence = "`" * max(4, fence_length)
            stream.write(f"## `{name}`\n\n{fence}{'text' if not contents.startswith('#!') else 'bash'}\n")
            stream.write(contents)
            if not contents.endswith("\n"):
                stream.write("\n")
            stream.write(f"{fence}\n\n")
    return zip_path, dump_path, names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path, default=Path("dist"))
    args = parser.parse_args()
    zip_path, dump_path, names = create_bundle(args.root, args.output_dir)
    print(f"Created {zip_path} ({len(names)} source files)")
    print(f"Created {dump_path} ({len(names)} source sections)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
